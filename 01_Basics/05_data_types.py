# 1. Integer (int)
age = 20
marks = 85
temperature = -5

print(age)
print(type(age))

print(marks)
print(type(marks))

print(temperature)
print(type(temperature))


# 2. Float (float)
height = 164.5
price = 99.99
weight = 62.0

print(height)
print(type(height))

print(price)
print(type(price))

print(weight)
print(type(weight))


# 3. String (str)
name = "Sejal"
city = "Pune"
course = "Python"

print(name)
print(type(name))

print(city)
print(type(city))

print(course)
print(type(course))


# 4. Boolean (bool)
is_student = True
is_working = False

print(is_student)
print(type(is_student))

print(is_working)
print(type(is_working))


# 5. Check multiple data types
a = 100
b = 10.5
c = "Hello"
d = True

print(type(a))
print(type(b))
print(type(c))
print(type(d))


# 6. Number versus string
number = 100
text = "100"

print(number)
print(type(number))

print(text)
print(type(text))