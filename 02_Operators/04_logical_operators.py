# 1. AND operator
print(True and True)
print(True and False)
print(False and True)
print(False and False)

# 2. OR operator
print(True or True)
print(True or False)
print(False or True)
print(False or False)

# 3. NOT operator
print(not True)
print(not False)

# 4. AND with comparisons
age = 20
print(age > 18 and age < 30)

# 5. OR with comparisons
age = 16
print(age < 18 or age > 60)

# 6. NOT with a comparison
age = 20
print(not age == 18)