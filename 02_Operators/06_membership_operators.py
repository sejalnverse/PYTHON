# 1. in operator with a string
text = "Python"

print("P" in text)
print("z" in text)

# 2. not in operator with a string
text = "Python"

print("z" not in text)
print("P" not in text)

# 3. in operator with a list
numbers = [10, 20, 30, 40]

print(20 in numbers)
print(50 in numbers)

# 4. not in operator with a list
numbers = [10, 20, 30, 40]

print(50 not in numbers)
print(10 not in numbers)

# 5. Membership with a word
fruits = ["apple", "banana", "mango"]

print("apple" in fruits)
print("orange" in fruits)

# 6. Membership with a sentence
sentence = "I am learning Python"

print("Python" in sentence)
print("Java" not in sentence)